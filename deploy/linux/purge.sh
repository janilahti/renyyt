#!/bin/sh
# Retained, root-owned cleanup entry point; works after Python is autoremoved.
set -eu
control=/var/lib/renyyt-package
[ "$(id -u)" -eq 0 ] || { echo 'Run this command as root.' >&2; exit 1; }
[ -e "$control" ] || [ -L "$control" ] || exit 0
[ ! -L "$control" ] && [ -d "$control" ] && [ "$(stat -c %u "$control")" -eq 0 ] && [ "$(stat -c %a "$control")" = 700 ] || {
    echo 'Unsafe package control directory.' >&2; exit 1;
}
record=$control/state.json
[ ! -L "$record" ] && [ -f "$record" ] && [ "$(stat -c %u "$record")" -eq 0 ] && [ "$(stat -c %a "$record")" = 600 ] || {
    echo 'Unsafe package ownership record.' >&2; exit 1;
}
# The JSON is generated by the package, root-only, with one scalar per line.
field() { sed -n 's/^  "'"$1"'": \([^,]*\),\{0,1\}$/\1/p' "$record"; }
[ "$(field schema)" = 1 ] || { echo 'Unsupported ownership schema.' >&2; exit 1; }
format=$(field format)
case "$format" in '"deb"') format=deb ;; '"rpm"') format=rpm ;; *) exit 1 ;; esac
user_created=$(field user_created)
group_created=$(field group_created)
case "$user_created:$group_created" in true:true|true:false|false:true|false:false) ;; *) exit 1 ;; esac
uid=$(field uid)
gid=$(field gid)
if [ "$user_created" = true ]; then
    case "$uid" in ''|*[!0-9]*|0) exit 1 ;; esac
    current=$(getent passwd renyyt | cut -d: -f3)
    [ -z "$current" ] || [ "$current" = "$uid" ] || { echo 'User identity changed; refusing deletion.' >&2; exit 1; }
fi
if [ "$group_created" = true ]; then
    case "$gid" in ''|*[!0-9]*|0) exit 1 ;; esac
    current=$(getent group renyyt | cut -d: -f3)
    [ -z "$current" ] || [ "$current" = "$gid" ] || { echo 'Group identity changed; refusing deletion.' >&2; exit 1; }
fi
if [ "${1:-}" != '--state-only' ]; then
    if [ -x /usr/bin/python3 ]; then
        exec /usr/bin/python3 "$control/purge.py"
    fi
    if [ "$format" = deb ]; then
        status=$(dpkg-query -W '-f=${db:Status-Status}' renyyt 2>/dev/null || :)
        if [ -n "$status" ] && [ "$status" != not-installed ]; then
            # Its postrm purge hook is shell-only too, so no Python is required.
            dpkg --purge renyyt
            [ -d "$control" ] || exit 0
        fi
    elif rpm -q --quiet renyyt; then
        echo 'Installed RPM requires Python; repair its dependencies before purge.' >&2
        exit 1
    fi
fi
if [ -d /run/systemd/system ]; then
    for unit in renyyt.service renyyt-reminders.service renyyt-reminders.timer; do
        loaded=$(systemctl show "$unit" --property=LoadState --value 2>/dev/null) || {
            [ "$loaded" = not-found ] || exit 1;
        }
        if [ "$loaded" != not-found ]; then
            systemctl stop "$unit"
            systemctl disable "$unit"
        fi
    done
fi
remove_directory() {
    [ -e "$1" ] || [ -L "$1" ] || return 0
    [ ! -L "$1" ] && [ -d "$1" ] || { echo "Refusing recursive cleanup of $1" >&2; exit 1; }
    rm -rf -- "$1"
}
remove_directory /var/lib/renyyt
for suffix in '' .rpmsave .rpmnew .dpkg-old .dpkg-dist .dpkg-new; do
    path=/etc/renyyt.env$suffix
    [ ! -d "$path" ] || [ -L "$path" ] || exit 1
    rm -f -- "$path"
done
if [ -e /etc/renyyt ] || [ -L /etc/renyyt ]; then
    [ ! -L /etc/renyyt ] && [ -d /etc/renyyt ] && [ "$(stat -c %u /etc/renyyt)" -eq 0 ] && [ "$(stat -c %a /etc/renyyt)" = 700 ] || exit 1
    for suffix in '' .rpmsave .rpmnew .dpkg-old .dpkg-dist .dpkg-new; do
        path=/etc/renyyt/renyyt.env$suffix
        [ ! -d "$path" ] || [ -L "$path" ] || exit 1
        rm -f -- "$path"
    done
    rmdir /etc/renyyt 2>/dev/null || :
fi
for unit in renyyt.service renyyt-reminders.service renyyt-reminders.timer; do
    remove_directory "/etc/systemd/system/$unit.d"
    rm -f -- "/etc/systemd/system/$unit"
done
if [ "$user_created" = true ] && getent passwd renyyt >/dev/null; then userdel renyyt; fi
if [ "$group_created" = true ] && getent group renyyt >/dev/null; then groupdel renyyt; fi
if [ -d /run/systemd/system ]; then
    systemctl daemon-reload
    systemctl reset-failed renyyt.service 2>/dev/null || :
fi
remove_directory "$control"
echo 'Renyyt package-owned state purged.'
